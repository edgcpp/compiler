/**
 * @brief Allocates memory for a C++ exception payload plus its prepended header.
 * @details Delegates to `allocate_exception_impl` and calls `std::terminate()` on OOM.
 * @param[in] thrown_size Size in bytes of the thrown object.
 * @return Pointer to the exception payload buffer.
 */
void *__cxa_allocate_exception(std::size_t thrown_size) noexcept {
    void *payload = nullptr;
    if (allocate_exception_impl(thrown_size, 0, &payload) != GCC_GEN_BE_SUCCESS || !payload) {
        std::terminate();
    }
    return payload;
}

/**
 * @brief Frees an exception payload buffer previously allocated by `__cxa_allocate_exception`.
 * @details Delegates to `free_exception_impl`.
 * @param[in] thrown_exception Pointer to the exception payload buffer.
 */
void __cxa_free_exception(void *thrown_exception) noexcept {
    (void)free_exception_impl(thrown_exception);
}

/**
 * @brief Allocates a dependent exception envelope for `std::rethrow_exception`.
 * @details Delegates to `allocate_exception_impl` with `is_dependent = 1`.
 * @return Pointer to the dependent exception envelope.
 */
void *__cxa_allocate_dependent_exception(void) noexcept {
    void *payload = nullptr;
    if (allocate_exception_impl(sizeof(void *), 1, &payload) != GCC_GEN_BE_SUCCESS || !payload) {
        std::terminate();
    }
    return payload;
}

/**
 * @brief Frees a dependent exception envelope previously allocated by `__cxa_allocate_dependent_exception`.
 * @details Delegates to `free_exception_impl`.
 * @param[in] dependent_exception Pointer to the dependent exception envelope.
 */
void __cxa_free_dependent_exception(void *dependent_exception) noexcept {
    (void)free_exception_impl(dependent_exception);
}

/**
 * @brief Initiates exception unwinding to the innermost registered SjLj frame.
 * @details Records `tinfo` and `dest` in the exception header, increments `uncaught_exc_count`,
 * pops the top frame from `__gcc_be_eh_chain`, populates its `exception_object` and `type_info` fields, and `longjmp`s.
 * @param[in] thrown_exception Pointer to the initialized exception payload.
 * @param[in] tinfo Pointer to the `std::type_info` descriptor of the thrown type.
 * @param[in] dest Optional destructor function pointer for the thrown object.
 */
void __cxa_throw(void *thrown_exception, void *tinfo, void (*dest)(void *)) {
    if (thrown_exception) {
        gcc_be_exc_header *hdr = reinterpret_cast<gcc_be_exc_header *>(
            static_cast<char *>(thrown_exception) - sizeof(gcc_be_exc_header));
        hdr->tinfo = tinfo;
        hdr->dtor = dest;
    }
    uncaught_exc_count++;
    current_landing_exc = thrown_exception;
    current_landing_tinfo = tinfo;

    gcc_be_sjlj_frame *frame = static_cast<gcc_be_sjlj_frame *>(__gcc_be_eh_chain);
    if (!frame) {
        std::terminate();
    }
    __gcc_be_eh_chain = frame->next;
    frame->exception_object = thrown_exception;
    frame->type_info = tinfo;
    std::longjmp(*reinterpret_cast<std::jmp_buf *>(frame->jmpbuf), 1);
}

/**
 * @brief Rethrows the currently active caught exception (`throw;`).
 * @details Retrieves the top exception from `active_exc_stack` and transfers control to the
 * next enclosing SjLj frame.
 */
void __cxa_rethrow(void) {
    if (active_exc_depth <= 0) {
        std::terminate();
    }
    void *exc = active_exc_stack[active_exc_depth - 1];
    void *tinfo = active_tinfo_stack[active_exc_depth - 1];
    if (exc) {
        gcc_be_exc_header *hdr = reinterpret_cast<gcc_be_exc_header *>(
            static_cast<char *>(exc) - sizeof(gcc_be_exc_header));
        hdr->handler_count++;
    }
    __cxa_throw(exc, tinfo, nullptr);
}


/*
a_bigint must be large enough to hold the binary representation of the absolute
value of the largest floating-point value.  Values are stored as an array of
unsigned integral values.  a_bigint_uint and a_bigint_int are unsigned and
signed integral types with at least twice as many bits as will be stored in
each bigint_word.

Note that a_bigint is a data structure with a fixed size, and as such
places a limit on the maximum value that can be represented.  The configuration
below uses the size of the largest floating-point type to come up with
an appropriately-sized a_bigint, but it's possible to specify a long string
of text digits that won't fit in whatever fixed size is chosen.  This can
introduce conversions that are off by a single bit.  A larger buffer
(i.e., BIGINT_WORDS) makes this possibility smaller.

The value of BIGINT_WORD_BYTES determines the values of these macros and the
types named by the three typedefs.

BIGINT_WORD_BITS is the number of bits to be stored in each array element.

BIGINT_WORD_MASK is used to extract the low order BIGINT_WORD_BITS from a
value for storage in the internal array.

BIGINT_WORD_MAX is the largest value that can be stored in an array element.

BIGINT_WORD_STORAGE_BYTES is the number of bytes that each word of storage
occupies; it is needed for memset and memcpy.

BIGINT_MAX_BITS is the size of the internal array in bits.
BIGINT_MAX_DIGITS is the size of the internal array in decimal digits.
BIGINT_WORDS is the size of the internal array in words.

a_bigint_word is an unsigned integral type whose size is at least
BIGINT_WORD_BITS.
*/

#define BIGINT_WORD_BITS (int)(BIGINT_WORD_BYTES * BYTE_SIZE)
#define BIGINT_WORD_MASK (((a_bigint_uint)1 << BIGINT_WORD_BITS) - 1)
#define BIGINT_WORD_MAX (a_bigint_uint)BIGINT_WORD_MASK
#define BIGINT_WORD_STORAGE_BYTES sizeof(a_bigint_word)

#define BIGINT_MAX_BITS (FPT_LARGEST_MAX_EXP + 2 * FPT_LARGEST_MANT_DIG)
#define BIGINT_MAX_EXP PFLOG10_2times(BIGINT_MAX_BITS)
#define BIGINT_WORDS ((BIGINT_MAX_BITS + BIGINT_WORD_BITS - 1) / \
                                                              BIGINT_WORD_BITS)

/*
a_bigint holds large non-negative integer values.
*/
typedef struct a_bigint *a_bigint_ptr;
typedef struct a_bigint {
  a_bigint_ptr  next;   /* Link, used by the free list. */
  a_bigint_word words[BIGINT_WORDS];
                        /* The value, little-endian. */
  unsigned int  num_words;
                        /* Number of words in representation of the value.
                           0 when the value is zero. */
} a_bigint;


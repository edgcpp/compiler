/*
Definitions of fundamental properties for IEEE 754-2008 floating-point types.
The default values for the FPT_FLOAT_* macros reflect the IEEE 754-2008
"binary32" type (aka IEEE 754-1985 "single" format); FPT_DOUBLE_* macros
reflect the IEEE 754-2008 "binary64" type (aka IEEE 754-1985 "double" format).
The FPT_LONG_DOUBLE_* macros can vary widely by target machine, and as
explained above, two popular formats are pre-configured, but additional
formats can also be specified.  Here's a list of the properties of
pre-configured types:

  Property       binary32  binary64    binary128  80-bit extended
  --------       --------  --------    ---------  ---------------
  type              float    double  long double      long double
  nominal size         32        64          128               80
  precision bits       24        53          113               64
  has hidden bit        1         1            1                0

FPT_FLOAT80_* explicitly refers to the 80-bit extended format (which may
or may not correspond to a builtin type).  Likewise FPT_FLOAT128_* explicitly
refers to the binary128 format.
*/


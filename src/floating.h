/*
The value of the macro FP_USE_EMULATION determines whether the conversion code
uses native floating-point math (when FP_USE_EMULATION is FALSE) or emulated
floating-point math (when FP_USE_EMULATION is TRUE).  These host floating-
point operations are used only when determining approximate results for
floating-point conversion; integer math is used in all cases to do any
final adjustment needed to obtain a correct result.  Using native floating-
point math gives better performance (though floating-point conversion is
not typically a bottleneck for most programs), but some floating-point
differences can be seen (i.e., on a 64-bit Intel processor, one-bit errors
can be seen when using 64-bit mode due to differences between the SSE2
and x87 instructions used).  Defaults to TRUE (since that's most portable
and most likely to yield correct results).
*/
#ifndef FP_USE_EMULATION
#define FP_USE_EMULATION TRUE
#endif /* ifndef FP_USE_EMULATION */

/*
The value of the macro JAVA_STYLE_SHORTEST determines whether the conversion
code requires the shortest sequence of digits generated by the conversion code
to have at least two digits.  A value of FALSE allows 1-digit sequences; a
value of TRUE requires at least two digits.
*/
#ifndef JAVA_STYLE_SHORTEST
#define JAVA_STYLE_SHORTEST TRUE
#endif /* ifndef JAVA_STYLE_SHORTEST */

/*
As part of the underlying mechanism used during floating-point conversion,
it is necessary to store very large integer values (much larger than can
be stored in a single host integer type).  Internally, the a_bigint structure
is used for this task; it contains an array of unsigned integers
to hold components of the integer value.  The types described here, namely,
FP_BIGINT_WORD_UNSIGNED_TYPE, FP_BIGINT_INTEGER_UNSIGNED_TYPE, and
FP_BIGINT_INTEGER_SIGNED_TYPE are used to implement the a_bigint type and
operations on a_bigint and are subject to the following restrictions.

FP_BIGINT_INTEGER_UNSIGNED_TYPE (used to perform arithmetic on the components
of the large integer) should specify the largest host unsigned integer type
available.  FP_BIGINT_INTEGER_SIGNED_TYPE should be the host signed integer
version of FP_BIGINT_INTEGER_UNSIGNED_TYPE.

FP_BIGINT_WORD_UNSIGNED_TYPE (used to store components of the large integer)
should specify a host unsigned integer type whose size is exactly half that
of FP_BIGINT_INTEGER_UNSIGNED_TYPE.  If no such type exists, then
FP_BIGINT_WORD_UNSIGNED_TYPE can be set to a larger host unsigned integer
type, however, in this case BIGINT_WORD_BYTES must be set to a value that
represents half of the size of the FP_BIGINT_INTEGER_UNSIGNED_TYPE type.
*/

#ifndef FP_BIGINT_INTEGER_UNSIGNED_TYPE
#define FP_BIGINT_INTEGER_UNSIGNED_TYPE unsigned long long
#endif /* ifndef FP_BIGINT_INTEGER_UNSIGNED_TYPE */

#ifndef FP_BIGINT_INTEGER_SIGNED_TYPE
#define FP_BIGINT_INTEGER_SIGNED_TYPE long long
#endif /* ifndef FP_BIGINT_INTEGER_SIGNED_TYPE */

#ifndef FP_BIGINT_WORD_UNSIGNED_TYPE
#define FP_BIGINT_WORD_UNSIGNED_TYPE unsigned int
#endif /* ifndef FP_BIGINT_WORD_UNSIGNED_TYPE */

#ifndef BIGINT_WORD_BYTES
#define BIGINT_WORD_BYTES sizeof(FP_BIGINT_WORD_UNSIGNED_TYPE)
#endif /* ifndef BIGINT_WORD_BYTES */

typedef FP_BIGINT_WORD_UNSIGNED_TYPE a_bigint_word;
typedef FP_BIGINT_INTEGER_UNSIGNED_TYPE a_bigint_uint;
typedef FP_BIGINT_INTEGER_SIGNED_TYPE a_bigint_int;

